import { readFile, writeFile } from "node:fs/promises"
import postcss from "postcss"

const css = await readFile("registry/styles/prose-syntax-theme.css", "utf8")
const classes = []
const encode = value => value.replaceAll("_", "\\_").replace(/\s+/g, "_")
// Parse nested media rules structurally; do not feed them to the flat Prose generator.
postcss.parse(css.replaceAll("--_syntax-", "--prose-syntax-internal-")).walkRules(rule => {
  let media = ""
  for (let parent = rule.parent; parent; parent = parent.parent) {
    if (parent.type === "atrule") media = `[@${parent.name}_${encode(parent.params)}]:` + media
  }
  for (const selector of rule.selectors) {
    // Explicit per-surface themes must win over ancestor themes regardless of Tailwind sorting.
    const variant = selector === ".honest-syntax" ? "" : `[${encode(selector.replaceAll(".honest-syntax", selector.startsWith(".honest-syntax[data-syntax-theme") ? "&&" : "&").replace(/="([\w-]+)"/g, "=$1"))}]:`
    rule.walkDecls(declaration => classes.push(`${media}${variant}[${declaration.prop}:${encode(declaration.value)}]!`))
  }
})
const output = `// Generated by npm run syntax:generate. Apply to the code surface.\nexport const syntaxTailwind = ${JSON.stringify(classes.join(" "), null, 2)}\n`
const path = "registry/lib/prose-syntax-tailwind.ts"
if (process.argv.includes("--check")) {
  if (await readFile(path, "utf8") !== output) throw new Error("Syntax Tailwind utilities are stale.")
} else await writeFile(path, output)
