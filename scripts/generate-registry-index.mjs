import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const projectRoot = process.cwd();
const examplesDirectory = path.join(projectRoot, "registry/examples");
const outputPath = path.join(projectRoot, "registry/__index__.tsx");

const files = (await readdir(examplesDirectory))
  .filter((file) => file.endsWith(".tsx"))
  .sort((a, b) => a.localeCompare(b));

const entries = await Promise.all(
  files.map(async (file, index) => {
    const name = file.slice(0, -4);
    const source = await readFile(path.join(examplesDirectory, file), "utf8");

    if (!/^export\s+default\b/m.test(source)) {
      throw new Error(`${file} needs a default export, which the docs preview renders.`);
    }

    return { name, identifier: `example${index}` };
  }),
);

const imports = entries
  .map(({ name, identifier }) => `import ${identifier} from "./examples/${name}";`)
  .join("\n");

const indexEntries = entries
  .map(({ name, identifier }) => `  ${JSON.stringify(name)}: { component: ${identifier} },`)
  .join("\n");

const output = `// This file is generated by \`npm run registry:index\`.\nimport type { ComponentType } from "react";\n\n${imports}\n\nexport const Index: Record<string, { component: ComponentType }> = {\n${indexEntries}\n};\n`;

await writeFile(outputPath, output);
console.log(`Indexed ${entries.length} examples.`);
